    SELECT 1 FROM pg_policies WHERE tablename = 'objects' AND policyname = 'Public Access to Receipts'
  ) THEN
    CREATE POLICY "Public Access to Receipts" ON storage.objects FOR SELECT USING (bucket_id = 'receipts');
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'objects' AND policyname = 'Allow Uploads to Receipts'
  ) THEN
    CREATE POLICY "Allow Uploads to Receipts" ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'receipts');
  END IF;
END
$$;
